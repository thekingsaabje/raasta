// Builds seed/seed.sql from research/sources.json (official-source research) plus clearly
// labelled TEST records and the configurable packages. Run: npm run seed:build
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const research = JSON.parse(readFileSync("research/sources.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const now = new Date().toISOString();
const out = ["-- GENERATED by scripts/build-seed.mjs. Do not edit by hand.", "DELETE FROM requirements; DELETE FROM packages;"];

for (const s of research.sources) {
  out.push(
    `INSERT OR REPLACE INTO sources (id, name, country, category, authority, url, language, applicant_groups, retrieval_method, last_success_at, review_status, notes) VALUES (${[
      s.id, s.name, s.country, s.category, s.authority, s.url, s.language, s.applicant_groups, "manual-research",
      s.reachable ? research.retrieved_on : null, s.reachable ? "discovered" : "inaccessible", s.notes,
    ].map(q).join(", ")});`,
  );
}

// Research rules are stored as text with evidence; they are not yet machine-checkable, so they
// use the "manual" rule kind and stay NEEDS_REVIEW until an admin verifies them.
for (const s of research.scholarships) {
  out.push(
    `INSERT OR REPLACE INTO scholarships (id, name, country, provider, source_id, official_url, levels, applicant_type, funding_summary, coverage, application_route, deadline_text, academic_year, status, is_test_data, retrieved_at, evidence_note, updated_at) VALUES (${[
      s.id, s.name, s.country, s.provider, s.source_id, s.official_url, JSON.stringify(s.levels ?? []), s.applicant_type ?? "new",
      [s.funding_summary, s.monthly_stipend_text ? `Stipend (as published): ${s.monthly_stipend_text}` : null].filter(Boolean).join(" "),
      "{}", s.application_route, s.deadline_text, s.academic_year, "NEEDS_REVIEW", 0, research.retrieved_on, s.evidence_note, now,
    ].map(q).join(", ")});`,
  );
  (s.key_requirements ?? []).forEach((r, i) => {
    out.push(
      `INSERT INTO requirements (id, scholarship_id, type, rule, text, excerpt, source_url, review_status, retrieved_at) VALUES (${[
        `${s.id}-r${i + 1}`, s.id, r.type, JSON.stringify({ kind: "manual" }), r.text, r.excerpt, s.official_url, "NEEDS_REVIEW", research.retrieved_on,
      ].map(q).join(", ")});`,
    );
  });
}

// TEST records: show how structured rules drive the eligibility engine. Not real scholarships.
const tests = [
  {
    id: "test-cn-master", name: "[TEST] Sample China Master's Award", country: "CN", provider: "Sample University (test)", levels: ["master"],
    coverage: { tuition: "full", accommodation: "full", stipend: { amount: 3000, currency: "CNY", period: "month" }, paymentStarts: "after registration" },
    policy: "EDITING_ONLY",
    rules: [
      { kind: "nationality", allowed: ["PK"] }, { kind: "target_level", levels: ["master"] }, { kind: "degree_completed", level: "bachelor" },
      { kind: "min_grade", scale: "4", min: 2.8 }, { kind: "max_age", max: 35, asOf: "2027-09-01" },
      { kind: "language", anyOf: [{ test: "IELTS", min: 6 }, { test: "HSK", min: 4 }] }, { kind: "existing_scholarship", forbidden: true },
    ],
  },
  {
    id: "test-de-phd", name: "[TEST] Sample Germany Doctoral Grant", country: "DE", provider: "Sample Foundation (test)", levels: ["phd"],
    coverage: { tuition: "none", stipend: { amount: 1300, currency: "EUR", period: "month" } },
    policy: "DRAFTING_ALLOWED",
    rules: [
      { kind: "nationality", allowed: ["PK", "IN", "BD"] }, { kind: "target_level", levels: ["phd"] }, { kind: "degree_completed", level: "master" },
      { kind: "min_experience_years", min: 2 }, { kind: "max_gap_years", max: 6 },
    ],
  },
];
for (const t of tests) {
  out.push(
    `INSERT OR REPLACE INTO scholarships (id, name, country, provider, official_url, levels, applicant_type, funding_summary, coverage, status, writing_policy, is_test_data, evidence_note, updated_at) VALUES (${[
      t.id, t.name, t.country, t.provider, "https://example.org/raasta-test-record", JSON.stringify(t.levels), "new",
      "TEST DATA. Demonstrates structured rules; not a real opportunity.", JSON.stringify(t.coverage), "UNKNOWN", t.policy, 1,
      "Test record for demonstrating the eligibility engine.", now,
    ].map(q).join(", ")});`,
  );
  t.rules.forEach((r, i) =>
    out.push(
      `INSERT INTO requirements (id, scholarship_id, type, rule, text, excerpt, source_url, review_status) VALUES (${[
        `${t.id}-r${i + 1}`, t.id, r.kind, JSON.stringify(r), `Test rule: ${r.kind.replace(/_/g, " ")}`, "TEST DATA", "https://example.org/raasta-test-record", "VERIFIED",
      ].map(q).join(", ")});`,
    ),
  );
}

const { DEFAULT_PACKAGES } = await import("../shared/packages.ts").catch(() => ({ DEFAULT_PACKAGES: null }));
const pkgs = DEFAULT_PACKAGES ?? JSON.parse(readFileSync("seed/packages.json", "utf8"));
pkgs.forEach((p, i) =>
  out.push(`INSERT INTO packages (id, name, price_pkr, period, summary, features, exclusions, sort) VALUES (${[p.id, p.name, p.price_pkr, p.period, p.summary, JSON.stringify(p.features), JSON.stringify(p.exclusions), i].map(q).join(", ")});`),
);

mkdirSync("seed", { recursive: true });
writeFileSync("seed/seed.sql", out.join("\n") + "\n");
console.log(`seed.sql: ${research.sources.length} sources, ${research.scholarships.length} researched scholarships, ${tests.length} test records, ${pkgs.length} packages`);
