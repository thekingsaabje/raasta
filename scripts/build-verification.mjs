// Turns research/verification.json into seed/verification-update.sql: an idempotent, history-preserving update.
// Never deletes human-verified rules, never runs the original seed. Run: node scripts/build-verification.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { parseRule, levelsFromText } from "../shared/rules.ts";

const V = JSON.parse(readFileSync("research/verification.json", "utf8"));
const MARK = `[evidence-check ${V.checked_on}]`;
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const STATUSES = new Set(["VERIFIED_OPEN", "VERIFIED_UPCOMING", "VERIFIED_CLOSED", "CANCELLED", "NEEDS_REVIEW", "CONFLICTING_SOURCES", "UNKNOWN"]);
const FUND = new Set(["full", "partial", "tuition_only", "stipend_only", "unknown"]);
const SCOPES = new Set(["scholarship_eligibility", "admission", "selection", "financial", "visa"]);
const KINDS = new Set(["nationality", "nationality_excluded", "residence_excluded", "target_level", "degree_completed", "min_grade", "max_age", "language", "max_gap_years", "existing_scholarship", "applicant_type", "min_experience_years", "field", "manual"]);
const date = (d) => (typeof d === "string" && /^\d{4}-\d{2}-\d{2}$/.test(d) ? d : null);
const now = new Date().toISOString();
const out = [`-- GENERATED by scripts/build-verification.mjs from research/verification.json (${V.checked_on}). Idempotent.`];
const stats = { updated: 0, verified: 0, rules: 0, verifiedRules: 0, tasks: 0, added: 0, sources: 0 };

function coverageOf(c) {
  if (!c || typeof c !== "object") return null;
  const ok = {};
  for (const k of ["tuition", "accommodation", "insurance", "travel"]) if (typeof c[k] === "string") ok[k] = c[k];
  if (c.stipend && typeof c.stipend.amount === "number" && c.stipend.currency && c.stipend.period) ok.stipend = { amount: c.stipend.amount, currency: c.stipend.currency, period: c.stipend.period };
  return Object.keys(ok).length ? JSON.stringify(ok) : null;
}

function rulesSql(sid, rec, currentCycle) {
  (rec.rules ?? []).forEach((r, i) => {
    const kind = r.machine_rule?.kind;
    const parsed = kind && KINDS.has(kind) ? parseRule(r.machine_rule) : null;
    if (kind && kind !== "manual" && !parsed) stats.malformed = (stats.malformed ?? 0) + 1;
    const rule = parsed ?? { kind: "manual" };
    // "Master applicants need â€¦" â†’ only applies to students aiming for that level.
    const lv = rule.kind === "target_level" ? undefined : levelsFromText(r.applies_to) ?? levelsFromText(r.text_en);
    if (lv && !rule.forLevels) rule.forLevels = lv;
    const verbatim = typeof r.excerpt_verbatim === "string" && r.excerpt_verbatim.trim().length > 0;
    // A rule can reject a student only when it comes from a confirmed CURRENT (open/upcoming) cycle with a
    // verbatim quote and valid structure. Rules from closed calls stay NEEDS_REVIEW for the next cycle.
    const review = currentCycle && verbatim && (parsed || rule.kind === "manual") ? "VERIFIED" : "NEEDS_REVIEW";
    stats.rules++;
    if (review === "VERIFIED") stats.verifiedRules++;
    const ev = (rec.evidence ?? []).find((e) => e.url === r.source_url) ?? (rec.evidence ?? [])[0] ?? {};
    out.push(
      `INSERT INTO requirements (id, scholarship_id, type, rule, text, excerpt, original_excerpt, source_url, applies_to, mandatory, review_status, retrieved_at, verified_at, scope, fetch_method) VALUES (${[
        `${sid}-v${i + 1}`, sid, r.type ?? kind ?? "other", JSON.stringify(rule), r.text_en ?? r.excerpt_verbatim ?? "See official page",
        verbatim ? r.excerpt_verbatim.slice(0, 600) : null, r.original_excerpt ?? null, r.source_url ?? ev.url ?? null, r.applies_to ?? null, 1,
        review, ev.fetched ?? V.checked_on, review === "VERIFIED" ? V.checked_on : null, SCOPES.has(r.scope) ? r.scope : "scholarship_eligibility", ev.method ?? null,
      ].map(q).join(", ")})
      ON CONFLICT(id) DO UPDATE SET rule = excluded.rule, review_status = excluded.review_status, verified_at = excluded.verified_at, scope = excluded.scope
      WHERE requirements.id NOT IN (SELECT entity_id FROM record_history WHERE entity = 'requirement' AND changed_by IS NOT NULL AND changed_by != 'research-agent');`,
    );
  });
}

function task(kind, sid, detail) {
  stats.tasks++;
  out.push(`INSERT OR IGNORE INTO review_tasks (kind, scholarship_id, detail, dedupe_key, created_at) VALUES ('${kind}', ${q(sid)}, ${q(detail.slice(0, 800))}, ${q(`${kind}:${sid}:${V.checked_on}`)}, ${q(now)});`);
}

for (const rec of V.scholarships ?? []) {
  const sid = rec.id;
  const status = STATUSES.has(rec.status_proposed) ? rec.status_proposed : "NEEDS_REVIEW";
  const verified = status.startsWith("VERIFIED_");
  const hasVerbatim = (rec.evidence ?? []).some((e) => e.excerpt_verbatim);
  // Research evidence never verifies a record: the stored status is always NEEDS_REVIEW (or CONFLICTING/CANCELLED).
  // The cycle the page shows is recorded by scripts/build-status-sync.mjs (cycle_state / proposed_deadline).
  const finalStatus = status === "CONFLICTING_SOURCES" || status === "CANCELLED" ? status : "NEEDS_REVIEW";
  const evidenceFound = verified && hasVerbatim;
  const isVerified = false;
  const deadline = date(rec.deadline_date);
  const guard = `id = ${q(sid)} AND COALESCE(evidence_note, '') NOT LIKE ${q(`%${MARK}%`)}`;
  stats.updated++;
  if (isVerified) stats.verified++;
  out.push(
    `INSERT INTO record_history (entity, entity_id, version, snapshot, changed_by, reason, changed_at) SELECT 'scholarship', id, version, json_object('status', status, 'deadline_date', deadline_date, 'deadline_text', deadline_text, 'academic_year', academic_year, 'funding_class', funding_class, 'coverage', coverage, 'evidence_note', evidence_note), 'research-agent', ${q(`Evidence check ${V.checked_on}`)}, ${q(now)} FROM scholarships WHERE ${guard};`,
    `INSERT INTO record_history (entity, entity_id, version, snapshot, changed_by, reason, changed_at) SELECT 'requirement', r.id, r.version, json_object('text', r.text, 'excerpt', r.excerpt, 'review_status', r.review_status), 'research-agent', ${q(`Superseded by evidence check ${V.checked_on}`)}, ${q(now)} FROM requirements r JOIN scholarships s ON s.id = r.scholarship_id WHERE s.${guard} AND r.review_status != 'VERIFIED';`,
    // Old research rules are replaced only when the new check produced rules of its own.
    ...((rec.rules ?? []).length
      ? [`DELETE FROM requirements WHERE scholarship_id = ${q(sid)} AND review_status != 'VERIFIED' AND id NOT LIKE ${q(`${sid}-v%`)} AND EXISTS (SELECT 1 FROM scholarships WHERE ${guard});`]
      : []),
    `UPDATE scholarships SET status = ${q(finalStatus)}, academic_year = COALESCE(${q(rec.academic_year)}, academic_year), deadline_date = ${q(isVerified ? deadline : null)},
      deadline_text = COALESCE(${q(rec.deadline_text_verbatim)}, deadline_text), funding_class = ${q(FUND.has(rec.funding_class) ? rec.funding_class : "unknown")},
      coverage = COALESCE(${q(coverageOf(rec.coverage))}, coverage), monitor_url = ${q(rec.monitor_url ?? null)},
      verification_method = ${evidenceFound ? "'agent_evidence'" : "NULL"}, last_verified_at = last_verified_at,
      evidence_note = ${q(`${MARK} ${rec.notes ?? ""}`.slice(0, 1900))}, version = version + 1, updated_at = ${q(now)} WHERE ${guard};`,
  );
  rulesSql(sid, rec, false); // research rules never reject a student; an admin verifies them
  if (!isVerified) task("verify_record", sid, `${finalStatus}: ${rec.notes ?? "needs human verification"}`);
  if (rec.monitor_url) {
    stats.sources++;
    out.push(`INSERT OR IGNORE INTO sources (id, name, country, category, url, retrieval_method, review_status, notes) SELECT ${q(`mon-${sid}`)}, 'Deadline page: ' || name, country, 'scholarship_page', ${q(rec.monitor_url)}, 'monitor', 'discovered', 'Deadline-bearing page registered for monitoring' FROM scholarships WHERE id = ${q(sid)} AND NOT EXISTS (SELECT 1 FROM sources WHERE url = ${q(rec.monitor_url)});`);
  }
}

for (const rec of V.new_scholarships ?? []) {
  if (!rec.id || !rec.name || !rec.official_url || !["CN", "DE", "IT"].includes(rec.country)) continue;
  const status = STATUSES.has(rec.status_proposed) ? rec.status_proposed : "NEEDS_REVIEW";
  const hasVerbatim = (rec.evidence ?? []).some((e) => e.excerpt_verbatim);
  const finalStatus = status === "CONFLICTING_SOURCES" || status === "CANCELLED" ? status : "NEEDS_REVIEW";
  const evidenceFound = status.startsWith("VERIFIED_") && hasVerbatim;
  const isVerified = false;
  stats.added++;
  out.push(
    `INSERT OR IGNORE INTO scholarships (id, name, country, provider, official_url, levels, applicant_type, funding_summary, coverage, application_route, deadline_date, deadline_text, academic_year, status, funding_class, verification_method, last_verified_at, monitor_url, is_test_data, retrieved_at, evidence_note, updated_at) VALUES (${[
      rec.id, rec.name, rec.country, rec.provider ?? rec.name, rec.official_url, JSON.stringify(rec.levels ?? []), ["new", "continuing", "both"].includes(rec.applicant_type) ? rec.applicant_type : "new",
      rec.funding_summary ?? null, coverageOf(rec.coverage) ?? "{}", rec.application_route ?? null, isVerified ? date(rec.deadline_date) : null, rec.deadline_text_verbatim ?? null,
      rec.academic_year ?? null, finalStatus, FUND.has(rec.funding_class) ? rec.funding_class : "unknown", evidenceFound ? "agent_evidence" : null, null,
      rec.monitor_url ?? null, 0, V.checked_on, `${MARK} ${rec.notes ?? ""}`.slice(0, 1900), now,
    ].map(q).join(", ")});`,
  );
  rulesSql(rec.id, rec, false);
  if (!isVerified) task("verify_record", rec.id, `${finalStatus}: ${rec.notes ?? "new record, needs human verification"}`);
}

writeFileSync("seed/verification-update.sql", out.join("\n") + "\n");
console.log(JSON.stringify(stats));
