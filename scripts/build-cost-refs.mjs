// research/finance-sources.json → seed/cost-references.sql (reference data only; safe to re-run).
// Run: npm run refs:build
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const D = JSON.parse(readFileSync("research/finance-sources.json", "utf8"));
// Later research rounds add items in a separate file; ids must not collide.
if (existsSync("research/finance-sources-additions.json")) {
  const add = JSON.parse(readFileSync("research/finance-sources-additions.json", "utf8"));
  const seen = new Set(D.items.map((i) => i.id));
  for (const i of add.items ?? []) {
    if (seen.has(i.id)) throw new Error(`duplicate reference id ${i.id}`);
    seen.add(i.id);
    D.items.push(i);
  }
}
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const STATUS = new Set(["VERIFIED", "OFFICIAL_ESTIMATE", "NEEDS_REVIEW"]);
const UNIT = new Set(["once", "month", "semester", "year"]);
const out = ["-- GENERATED by scripts/build-cost-refs.mjs. Reference figures with verbatim official evidence.", "DELETE FROM cost_references;"];
let n = 0;
for (const i of D.items) {
  if (!i.id || !["DE", "IT", "CN", "PK"].includes(i.country) || !UNIT.has(i.unit) || !STATUS.has(i.status)) continue;
  // A figure without a verbatim quote can't be marked verified.
  const status = i.status === "VERIFIED" && !i.excerpt_verbatim ? "NEEDS_REVIEW" : i.status;
  out.push(
    `INSERT INTO cost_references (id, country, kind, category, label, amount, amount_max, currency, unit, applies_to, authority, source_url, excerpt, status, checked_at, evidence_types, notes) VALUES (${[
      i.id, i.country, i.kind === "proof_of_funds" ? "proof_of_funds" : "cost", i.category, i.label, i.amount, i.amount_max, i.currency, i.unit,
      i.applies_to, i.authority, i.source_url, i.excerpt_verbatim, status, i.fetched ?? D.checked_on, i.evidence_types ? JSON.stringify(i.evidence_types) : null, i.notes,
    ].map(q).join(", ")});`,
  );
  n++;
}
writeFileSync("seed/cost-references.sql", out.join("\n") + "\n");
console.log(`cost-references.sql: ${n} items`);
