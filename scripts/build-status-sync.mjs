// research/verification.json → seed/status-sync.sql. Idempotent; safe to re-run on live.
// Policy: research (AI-extracted) evidence never makes a record or rule "verified". The cycle the official page
// shows goes into cycle_state / proposed_deadline; status stays NEEDS_REVIEW until an admin confirms it.
// Records an admin already confirmed (verification_method = 'human') are never touched.
import { readFileSync, writeFileSync } from "node:fs";

const V = JSON.parse(readFileSync("research/verification.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const date = (d) => (typeof d === "string" && /^\d{4}-\d{2}-\d{2}$/.test(d) ? d : null);
const fmt = (d) => new Date(d + "T00:00:00Z").toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
const now = new Date().toISOString();
const CYCLE = { VERIFIED_OPEN: "open", VERIFIED_UPCOMING: "upcoming", VERIFIED_CLOSED: "closed" };

// Why each record that the research could not tie to a current call is still unverified (plain English).
const REASONS = {
  "cn-cgs-csc-general": "The CSC guide has no single deadline: each agency and university sets its own, so there is no date to confirm yet.",
  "cn-shanghai-gov-a": "The funding amounts are published only as an image we could not read, and each university sets its own dates.",
  "cn-shanghai-gov-b": "The funding amounts are published only as an image we could not read, and each university sets its own dates.",
  "cn-beijing-gov": "The call covers three categories with different funding (A full, B no living costs, C tuition and insurance only) and gives no central deadline.",
  "de-daad-epos": "Each course sets its own deadline; DAAD's list just says \"see website of the course\".",
  "de-daad-study-all-disciplines": "Pakistan does not appear in DAAD's country list for this programme and no current deadline is published. Likely not open to applicants from Pakistan.",
  "de-daad-stem": "Pakistan is not in DAAD's country list for this programme. Likely not open to applicants from Pakistan.",
  "de-daad-helmut-schmidt": "The deadline was missing from the official PDF we read, and the selection runs in Oct/Nov 2026, so this round has probably closed.",
  "de-deutschlandstipendium": "Each university sets its own deadline; there is no single national date.",
  "de-fes": "Aimed at students already studying in Germany; the dated deadlines on the programme pages were not checked.",
  "de-kaad-programme-1": "Pakistan is not a KAAD focus country, so applications are accepted only in exceptional cases. No dates or amounts are published.",
  "it-unipd-excellence": "The next call (for 2027/28) is due in November 2026 and has not been published yet.",
  "it-unibo-international-talents": "Only last year's (2025-26) official call was found; the current call was not.",
  "de-kas-international": "Realistic mainly for students already in Germany with B2 German; no 2027 date is published.",
};

function reasonFor(rec, cycle, dl) {
  if (REASONS[rec.id]) return REASONS[rec.id];
  const year = rec.academic_year ? `${rec.academic_year} ` : "";
  const when = dl ? fmt(dl) : null;
  if (cycle === "open") return `The official page says the ${year}call is open${when ? ` until ${when}` : ""}. Our research quoted it word for word, but a Raasta reviewer has not confirmed it yet, so check the official page before relying on it.`;
  if (cycle === "upcoming") return `The official page says the ${year}call opens later${when ? ` (deadline ${when})` : ""}. Our research quoted it, but a reviewer has not confirmed it yet.`;
  if (cycle === "closed") return `The official page shows the ${year}round has closed${when ? ` (deadline was ${when})` : ""}. Watch for the next call. A reviewer has not confirmed this yet.`;
  return "We could not tie this record to a current official call yet; a reviewer needs to check it.";
}

const out = [`-- GENERATED by scripts/build-status-sync.mjs (${V.checked_on}). Idempotent. Skips reviewer-confirmed records.`];
const counts = { open: 0, upcoming: 0, closed: 0, unknown: 0 };
for (const rec of [...(V.scholarships ?? []), ...(V.new_scholarships ?? [])]) {
  const cycle = CYCLE[rec.status_proposed] ?? "unknown";
  counts[cycle]++;
  const dl = date(rec.deadline_date);
  const notHuman = `id = ${q(rec.id)} AND COALESCE(verification_method, '') != 'human'`;
  out.push(
    // History only the first time (while the record still carries a research-set VERIFIED_* status).
    `INSERT INTO record_history (entity, entity_id, version, snapshot, changed_by, reason, changed_at) SELECT 'scholarship', id, version, json_object('status', status, 'deadline_date', deadline_date, 'verification_method', verification_method), 'policy', 'Research evidence no longer counts as verification; awaiting reviewer', ${q(now)} FROM scholarships WHERE ${notHuman} AND status LIKE 'VERIFIED_%';`,
    `UPDATE scholarships SET version = version + (CASE WHEN status LIKE 'VERIFIED_%' THEN 1 ELSE 0 END),
      status = CASE WHEN status = 'CONFLICTING_SOURCES' OR status = 'CANCELLED' THEN status ELSE 'NEEDS_REVIEW' END,
      cycle_state = ${q(cycle)}, proposed_deadline = ${q(dl)}, deadline_date = NULL, last_verified_at = NULL,
      status_reason = ${q(reasonFor(rec, cycle, dl))}, updated_at = ${q(now)} WHERE ${notHuman};`,
    `INSERT OR IGNORE INTO review_tasks (kind, scholarship_id, detail, dedupe_key, created_at) SELECT 'verify_record', id, ${q(`Confirm against the official page. Research suggests: ${cycle}${dl ? `, deadline ${dl}` : ""}.`)}, ${q(`verify_record:${rec.id}:${V.checked_on}`)}, ${q(now)} FROM scholarships WHERE ${notHuman};`,
  );
}
// Research-verified rules on real records can no longer rule a student out; only an admin can verify them.
out.push(
  `UPDATE requirements SET review_status = 'NEEDS_REVIEW', verified_at = NULL WHERE review_status = 'VERIFIED'
    AND scholarship_id IN (SELECT id FROM scholarships WHERE is_test_data = 0 AND COALESCE(verification_method, '') != 'human')
    AND id NOT IN (SELECT entity_id FROM record_history WHERE entity = 'requirement' AND changed_by IS NOT NULL AND changed_by NOT IN ('research-agent', 'policy'));`,
);
writeFileSync("seed/status-sync.sql", out.join("\n") + "\n");
console.log(JSON.stringify(counts));
